"""Generate the placeholder registry (PLACEHOLDERS.md) from every PLACEHOLDER token and not_implemented() call.

Run: python tools/list_placeholders.py [--write PLACEHOLDERS.md]
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCAN = ("config", "src", "infra", "deploy", "evals")
SUFFIXES = {".py", ".yaml", ".yml", ".tf", ".tfvars", ".json", ".toml", ".sh", ".md", ".env", ".example"}
TOKEN = re.compile(r"PLACEHOLDER:(Q-\d{2}):([a-z][a-z0-9_]*)")
# not_implemented("Q-xx", "what") / placeholder("Q-xx", "name") — f-strings and line breaks allowed.
CALL = re.compile(r"\b(not_implemented|placeholder)\(\s*[\"'](Q-\d{2})[\"']\s*,\s*f?[\"']([^\"']+)[\"']", re.S)

QUESTIONS = {  # mirrors docs/15-risks-assumptions-open-questions.md
    "Q-01": "SLB Knowledge Base backend, API and publish workflow",
    "Q-02": "Figma plan/seats, private org plugin permission, MCP Catalog admission",
    "Q-03": "SLB DLS library keys, fonts and design tokens",
    "Q-04": "ADO process template: org/project, work-item types, fields, area paths",
    "Q-05": "ServiceNow instance, tables and integration user",
    "Q-06": "Figma Enterprise (variables API)",
    "Q-07": "PagerDuty account, services and auth model",
    "Q-08": "Workforce IdP (Entra ID) tenant and approver groups",
    "Q-09": "Data residency: non-regional model endpoints, retention",
    "Q-10": "GCP organization ID and stage/prod projects",
    "Q-11": "Approval to derive sanitized eval fixtures from the corpus",
    "Q-12": "Pilot product line and KPI baselines",
    "Q-13": "Mailboxes and OneDrive/SharePoint sites in scope",
    "Q-14": "Internal outreach shared mailbox",
    "Q-15": "Architecture/feasibility reference sources",
}


def collect() -> dict[str, dict[str, set[str]]]:
    """Map question id → placeholder name → files that reference it."""
    found: dict[str, dict[str, set[str]]] = defaultdict(lambda: defaultdict(set))
    for top in SCAN:
        base = ROOT / top
        if not base.exists():
            continue
        for path in sorted(base.rglob("*")):
            if not path.is_file() or path.suffix not in SUFFIXES or ".terraform" in path.parts:
                continue
            rel = path.relative_to(ROOT).as_posix()
            text = path.read_text(encoding="utf-8", errors="ignore")
            for qid, name in TOKEN.findall(text):
                found[qid][name].add(rel)
            for kind, qid, what in CALL.findall(text):
                if kind == "placeholder" and TOKEN.search(f"PLACEHOLDER:{qid}:{what}"):
                    found[qid][what].add(rel)
                else:
                    found[qid][f"code path: {what}"].add(rel)
    return found


def render(found: dict[str, dict[str, set[str]]]) -> str:
    """Render the registry as a markdown table."""
    lines = [
        "# Placeholder registry",
        "",
        "> Generated by `make placeholders` (tools/list_placeholders.py) — do not edit by hand.",
        "> This repository is a **reference architecture**: SLB-specific details that are not known yet are carried as",
        "> `PLACEHOLDER:<question>:<name>` tokens (config, Terraform) or",
        "> `not_implemented(\"<question>\", ...)` code paths.",
        "> They are tolerated in `local`/`dev` and **rejected in `stage`/`prod`** (`pm_agent.settings.load_settings`).",
        "> Question ids refer to [docs/15](docs/15-risks-assumptions-open-questions.md).",
        "",
        "| Question | Topic | Placeholder | Where |",
        "|---|---|---|---|",
    ]
    total = 0
    for qid in sorted(found):
        for name in sorted(found[qid]):
            where = "<br/>".join(f"`{p}`" for p in sorted(found[qid][name]))
            lines.append(f"| {qid} | {QUESTIONS.get(qid, '—')} | `{name}` | {where} |")
            total += 1
    lines += ["", f"**{total} placeholders across {len(found)} open questions.**", ""]
    return "\n".join(lines)


def main() -> int:
    """CLI entry point: print the registry or write it with ``--write``."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", type=Path, help="write the markdown registry to this path")
    args = parser.parse_args()
    markdown = render(collect())
    if args.write:
        (ROOT / args.write).write_text(markdown, encoding="utf-8")
        print(f"wrote {args.write}")
    else:
        print(markdown)
    return 0


if __name__ == "__main__":
    sys.exit(main())
