"""Compile an approved ``PrototypeSpec`` into a Figma Plugin API program (ADR-006 Path A, docs/09 §6).

Figma's REST API cannot create canvas content, so the renderer emits a program that the private SLB Figma plugin
executes in the designer's file: DLS components are imported by key and instantiated (reuse first), text comes only
from verified requirement claims, and every string is JSON-escaped. Fonts are a placeholder until the SLB DLS fonts
and tokens are supplied (Q-03).
"""

from __future__ import annotations

import json

from pm_agent.schemas import PrototypeSpec, SpecNode
from pm_agent.schemas.subjects import subject_digest

PLACEHOLDER_FONT = {"family": "Inter", "style": "Regular"}  # PLACEHOLDER:Q-03:dls_font_family


def _js(value: object) -> str:
    return json.dumps(value, ensure_ascii=False)


class _Emitter:
    def __init__(self, claims: dict[str, str]) -> None:
        self.lines: list[str] = []
        self.components: dict[str, str] = {}
        self.claims = claims
        self.counter = 0

    def var(self, prefix: str) -> str:
        self.counter += 1
        return f"{prefix}_{self.counter}"

    def component(self, key: str) -> str:
        if key not in self.components:
            name = self.var("comp")
            self.components[key] = name
            self.lines.append(f"const {name} = await figma.importComponentByKeyAsync({_js(key)});")
        return self.components[key]

    def node(self, spec: SpecNode, parent: str) -> None:
        """Emit one spec node (instance by DLS key, claim text, or frame) and its children."""
        if spec.kind == "instance" and spec.component_key:
            name = self.var("inst")
            self.lines.append(f"const {name} = {self.component(spec.component_key)}.createInstance();")
            if spec.variant_props:
                self.lines.append(f"{name}.setProperties({_js(spec.variant_props)});")
        elif spec.kind == "text":
            name = self.var("text")
            text = self.claims.get(spec.text_claim_id or "", "")
            self.lines += [f"const {name} = figma.createText();", f"{name}.characters = {_js(text)};"]
        else:
            name = self.var("frame")
            self.lines += [f"const {name} = figma.createFrame();", f"{name}.layoutMode = \"VERTICAL\";"]
        self.lines += [f"{name}.name = {_js(spec.name)};", f"{parent}.appendChild({name});"]
        for child in spec.children:
            self.node(child, name)


def compile_plugin_program(spec: PrototypeSpec, claims: dict[str, str]) -> str:
    """Deterministic JavaScript for ``figma.*`` (claims: verified claim_id → text)."""
    emitter = _Emitter(claims)
    header = [f"// Generated by pm-agent svc-prototype-renderer from PrototypeSpec {spec.spec_id}",
              f"// subject {subject_digest(spec)} · DLS {spec.dls_library_file_key}@{spec.dls_published_version}",
              "// Do not edit: re-render from an approved spec instead.",
              f"await figma.loadFontAsync({_js(PLACEHOLDER_FONT)});",
              "const page = figma.createPage();",
              f"page.name = {_js('PM Agent / ' + spec.requirement_id)};"]
    for screen in spec.screens:
        frame = emitter.var("screen")
        emitter.lines += [f"const {frame} = figma.createFrame();", f"{frame}.name = {_js(screen.name)};",
                          f"{frame}.resize({int(screen.width)}, {int(screen.height)});", f"page.appendChild({frame});"]
        for node in screen.nodes:
            emitter.node(node, frame)
    return "\n".join(header + emitter.lines + ["figma.currentPage = page;"]) + "\n"
